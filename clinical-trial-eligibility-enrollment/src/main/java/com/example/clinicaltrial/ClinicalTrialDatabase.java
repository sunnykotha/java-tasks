package com.example.clinicaltrial;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.function.Function;
import java.util.Objects;

public final class ClinicalTrialDatabase {

    private final String jdbcUrl;

    public ClinicalTrialDatabase(String jdbcUrl) {
        if (jdbcUrl == null || jdbcUrl.isBlank()) {
            throw new IllegalArgumentException("JDBC URL must not be blank");
        }

        this.jdbcUrl = jdbcUrl;
        initializeSchema();
    }

    public Connection getConnection() throws SQLException {
        return DriverManager.getConnection(jdbcUrl);
    }

    public <T> T inTransaction(
            Function<Connection, T> operation
    ) {
        if (operation == null) {
            throw new IllegalArgumentException("Transaction operation is required");
        }

        try (Connection connection = getConnection()) {
            connection.setAutoCommit(false);

            try {
                T result = operation.apply(connection);
                connection.commit();
                return result;
            } catch (RuntimeException | Error exception) {
                try {
                    connection.rollback();
                } catch (SQLException rollbackException) {
                    exception.addSuppressed(rollbackException);
                }
                throw exception;
            } catch (SQLException exception) {
                try {
                    connection.rollback();
                } catch (SQLException rollbackException) {
                    exception.addSuppressed(rollbackException);
                }
                throw new IllegalStateException(
                    "Database transaction failed", exception
                );
            }
        } catch (SQLException exception) {
            throw new IllegalStateException(
                "Could not complete database transaction", exception
            );
        }
    }

    private void initializeSchema() {
        try (Connection connection = getConnection();
             Statement statement = connection.createStatement()) {

            statement.execute("""
                CREATE TABLE IF NOT EXISTS trial_capacity (
                    trial_id BIGINT PRIMARY KEY,
                    max_enrollment INT NOT NULL CHECK (max_enrollment > 0),
                    max_enrollment_per_site INT NOT NULL
                        CHECK (max_enrollment_per_site > 0)
                )
                """);

            statement.execute("""
                CREATE TABLE IF NOT EXISTS site_capacity (
                    site_id BIGINT PRIMARY KEY,
                    trial_id BIGINT NOT NULL,
                    closed BOOLEAN NOT NULL DEFAULT FALSE
                )
                """);

            statement.execute("""
                CREATE TABLE IF NOT EXISTS arm_capacity (
                    arm_id BIGINT PRIMARY KEY,
                    trial_id BIGINT NOT NULL,
                    max_enrollment INT NOT NULL CHECK (max_enrollment > 0),
                    closed BOOLEAN NOT NULL DEFAULT FALSE
                )
                """);

            statement.execute("""
                CREATE TABLE IF NOT EXISTS trial_enrollment (
                    enrollment_id BIGINT PRIMARY KEY,
                    patient_id BIGINT NOT NULL,
                    trial_id BIGINT NOT NULL,
                    site_id BIGINT NOT NULL,
                    arm_id BIGINT NOT NULL,
                    enrolled_at TIMESTAMP NOT NULL,
                    status VARCHAR(20) NOT NULL,
                    withdrawn_at TIMESTAMP,
                    CHECK (status IN ('ACTIVE', 'WITHDRAWN'))
                )
                """);

            statement.execute("""
                CREATE TABLE IF NOT EXISTS randomization_block (
                    block_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    site_id BIGINT NOT NULL,
                    sex VARCHAR(20) NOT NULL,
                    block_size INT NOT NULL CHECK (block_size > 0),
                    arm_a_id BIGINT NOT NULL,
                    arm_b_id BIGINT NOT NULL,
                    next_slot INT NOT NULL DEFAULT 0,
                    CHECK (arm_a_id <> arm_b_id),
                    CHECK (next_slot >= 0 AND next_slot <= block_size)
                )
                """);

            statement.execute("""
                CREATE TABLE IF NOT EXISTS randomization_assignment (
                    block_id BIGINT NOT NULL,
                    slot_index INT NOT NULL,
                    arm_id BIGINT NOT NULL,
                    consumed_by_enrollment_id BIGINT,
                    consumed_at TIMESTAMP,
                    PRIMARY KEY (block_id, slot_index),
                    UNIQUE (consumed_by_enrollment_id)
                )
                """);

        } catch (SQLException exception) {
            throw new IllegalStateException(
                "Could not initialize the clinical trial database",
                exception
            );
        }
    }
}